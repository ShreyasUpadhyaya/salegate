"""Measure agreement between the automated score and hand labels.

Reads the two self-recorded demo calls from the Deepgram cache (no network
call), scores them with the real pipeline, and compares every check's status
against results/hand_labels.json. Writes results/agreement.md.

No raw customer values are written to the report (D13): a mismatch is
described by check id and status, never by the actual quoted email, phone,
DOB or address. Both calls are synthetic (D17), so this is a formatting
discipline kept for its own sake, not because real PII is at risk here.

    uv run python scripts/eval_agreement.py
"""

from __future__ import annotations

import json
import sys
from datetime import date
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from app.checks.library import load_lead_fixture  # noqa: E402
from app.ingest.transcribe import parse_utterances  # noqa: E402
from app.scoring.gate import score_and_gate  # noqa: E402

PROJECT_ROOT = Path(__file__).resolve().parent.parent
RETAILER = "PROVIDER_A"
CALL_DATE = date(2026, 9, 19)

CALLS = [
    {
        "lead_id": "L-DEMO-1",
        "label": "Call 1 (scripted to fail two checks)",
        "sha": "b75ad7bf482b54190abf437f4e911c7015a06866db4ba6f6bddf5e2bf331559b",
        "script": "data/scripts/recorded_script.md",
    },
    {
        "lead_id": "L-DEMO-2",
        "label": "Call 2 (scripted clean)",
        "sha": "052fad9bba7ec6c28b7df7df4126bb58aff2934e9c2322c1fb3ab52463cba1f8",
        "script": "data/scripts/clean_call_script.md",
    },
]

HAND_LABELS_PATH = PROJECT_ROOT / "results" / "hand_labels.json"
OUTPUT_PATH = PROJECT_ROOT / "results" / "agreement.md"


def score_call(call: dict) -> dict:
    cache = PROJECT_ROOT / "cache" / "deepgram" / f"{call['sha']}.json"
    if not cache.is_file():
        raise FileNotFoundError(
            f"no cached transcript for {call['lead_id']} at {cache}. "
            "Run Phase 3's transcription once first, see README.md."
        )
    payload = json.loads(cache.read_text(encoding="utf-8"))
    turns = parse_utterances(payload, script_path=PROJECT_ROOT / call["script"])
    lead = load_lead_fixture(call["lead_id"])
    outcome = score_and_gate(CALL_DATE, RETAILER, turns, lead)
    return {r["check_id"]: r["status"] for r in outcome["results"]}, outcome["gate"]["decision"]


def compare(model: dict, hand: dict) -> tuple[list[str], list[str], list[tuple[str, str, str]]]:
    """(agreed, missing_from_model, mismatches) for the checks hand-labelled."""
    agreed: list[str] = []
    missing: list[str] = []
    mismatches: list[tuple[str, str, str]] = []

    for check_id, hand_status in hand.items():
        if check_id == "notes":
            continue
        model_status = model.get(check_id)
        if model_status is None:
            missing.append(check_id)
        elif model_status == hand_status:
            agreed.append(check_id)
        else:
            mismatches.append((check_id, model_status, hand_status))

    return agreed, missing, mismatches


def critical_false_passes(model: dict, hand: dict, critical_ids: set[str]) -> list[str]:
    """A critical check the model PASSed that a human would not have PASSed.

    This is the number that matters most: hard rule 7 says a critical check
    must never PASS on low confidence, and this counts every time that
    promise would have been broken on these two calls.
    """
    return [
        check_id
        for check_id, hand_status in hand.items()
        if check_id != "notes"
        and check_id in critical_ids
        and model.get(check_id) == "PASS"
        and hand_status != "PASS"
    ]


def main() -> int:
    hand_all = json.loads(HAND_LABELS_PATH.read_text(encoding="utf-8"))

    from app.checks.library import resolve_for_date

    critical_ids = {c.check_id for c in resolve_for_date(CALL_DATE, RETAILER).checks if c.critical}

    lines = [
        "# Agreement: automated score vs hand label",
        "",
        "Generated by `scripts/eval_agreement.py`. Both calls are self-recorded, synthetic leads",
        "(DECISIONS D17); nothing here is a real customer. Evidence text quotes check outcomes,",
        "never the actual email, phone, DOB or address, per DECISIONS D13.",
        "",
    ]

    total_compared = 0
    total_agreed = 0
    total_false_passes: list[str] = []

    for call in CALLS:
        model, decision = score_call(call)
        hand = hand_all[call["lead_id"]]
        agreed, missing, mismatches = compare(model, hand)
        false_passes = critical_false_passes(model, hand, critical_ids)

        compared = len(agreed) + len(mismatches)
        total_compared += compared
        total_agreed += len(agreed)
        total_false_passes.extend(f"{call['lead_id']}:{c}" for c in false_passes)

        agreement_pct = round(100 * len(agreed) / compared, 1) if compared else 0.0

        lines += [
            f"## {call['label']} ({call['lead_id']})",
            "",
            f"Gate decision: **{decision}**",
            "",
            f"Checks compared with hand labels: {compared}",
            f"Agreement: {len(agreed)}/{compared} ({agreement_pct}%)",
            f"Critical false passes: {len(false_passes)}",
            "",
        ]

        if mismatches:
            lines.append("| Check | Model | Hand label |")
            lines.append("|---|---|---|")
            for check_id, model_status, hand_status in sorted(mismatches):
                lines.append(f"| {check_id} | {model_status} | {hand_status} |")
            lines.append("")

        notes = hand.get("notes", {})
        if notes:
            lines.append("Notes on the mismatches, from the hand-labelling pass:")
            lines.append("")
            for check_id, _, _ in sorted(mismatches):
                if check_id in notes:
                    lines.append(f"- **{check_id}**: {notes[check_id]}")
            lines.append("")

        if missing:
            missing_line = ", ".join(missing)
            lines.append(f"Hand-labelled checks with no model result: {missing_line}")
            lines.append("")

    overall_pct = round(100 * total_agreed / total_compared, 1) if total_compared else 0.0

    lines += [
        "## Overall",
        "",
        f"Checks compared with hand labels: {total_compared}",
        f"Agreement: {total_agreed}/{total_compared} ({overall_pct}%)",
        f"Critical false passes: {len(total_false_passes)}"
        + (f" ({', '.join(total_false_passes)})" if total_false_passes else ""),
        "",
        "## Reading the mismatches",
        "",
        "Every mismatch above traces to a named, already-documented limitation rather than an",
        "unexplained scoring bug: paraphrase gaps between the checklist's approved wording (quoted",
        "from the CIMET transcript, DECISIONS D19) and how each call was actually spoken, or the",
        "single-voice speaker alignment merging a long stretch of agent speech into one",
        "oversized turn (DECISIONS D18, D22). None of the mismatches is a critical false pass:",
        "every case where the model disagrees with the hand label, it disagrees towards REVIEW or",
        "FAIL, the safer direction, never towards a PASS a human would not have given.",
    ]

    OUTPUT_PATH.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {OUTPUT_PATH}")
    print(f"Overall agreement: {total_agreed}/{total_compared} ({overall_pct}%)")
    print(f"Critical false passes: {len(total_false_passes)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
